import fs from 'node:fs';
import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
const dom=new JSDOM('',{runScripts:'outside-only'}), w=dom.window;
w.eval(fs.readFileSync('app/api.js','utf8'));
const requests=[], seen=[];
const store=w.FLApi.Store({snapshot:code=>new Promise(resolve=>requests.push({code,resolve}))});
const snapshot=(code,rev=1)=>({session:{code,rev},teams:[],runs:[]});
const flush=()=>new Promise(resolve=>setImmediate(resolve));
store.on(s=>seen.push(s?.session.code));
store.start('F2BY'); store.start('ZN8C'); assert.equal(requests.length,2);
requests[0].resolve(snapshot('F2BY')); await flush();
assert.equal(store.snap,null); assert.equal(store.busy,true); assert.equal(seen.length,0);
requests[1].resolve(snapshot('ZN8C')); await flush();
assert.equal(store.snap.session.code,'ZN8C'); assert.deepEqual(seen,['ZN8C']);
store.refresh(); store.stop(); requests[2].resolve(snapshot('ZN8C',2)); await flush();
assert.equal(store.snap,null); assert.equal(store.code,null); assert.deepEqual(seen,['ZN8C']);
store.start('CHTS'); requests[3].resolve(snapshot('F2BY')); await flush();
assert.equal(store.snap,null); assert.deepEqual(seen,['ZN8C']);
store.stop(); dom.window.close();
console.log('PASS: stale room responses, late responses after stop and wrong-room snapshots cannot replace current room data');
